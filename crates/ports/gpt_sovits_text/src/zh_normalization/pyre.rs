//! Helpers that reproduce the parts of Python's `re` and `str` that the
//! `zh_normalization` package relies on. This module has no Python counterpart.
//!
//! - [`PyRegex`] compiles a Python pattern source unchanged. It translates the few
//!   constructs whose meaning differs between Python `re` and the Rust regex
//!   crates (see `translate`), then uses `regex` when it can and `fancy-regex`
//!   when the pattern needs lookarounds or backreferences.
//! - [`PyMatch`] mirrors `re.Match.group()` / `re.Match.groups()`.
//! - [`py_strip`] and friends mirror `str.strip()` / `str.split()` with Python's
//!   definition of whitespace (`str.isspace`).

use std::sync::LazyLock;

use super::Error;

/// Code point ranges of Python 3.11 `re` `\d` (Unicode 14.0.0 category `Nd`),
/// generated by `parity/zh_normalization/convert_data.py`.
const PYTHON_DECIMAL_DIGITS: &str =
  include_str!("../../data/zh_normalization/python_decimal_digits.txt");

/// The body of a character class (without brackets) equivalent to Python's `\d`.
static DIGIT_CLASS_BODY: LazyLock<String> = LazyLock::new(|| {
  let mut out = String::new();
  for line in PYTHON_DECIMAL_DIGITS.lines() {
    let line = line.trim();
    if line.is_empty() || line.starts_with('#') {
      continue;
    }
    let (a, b) = line.split_once('-').expect("range line");
    out.push_str(&format!("\\x{{{a}}}-\\x{{{b}}}"));
  }
  out
});

/// Translate a Python `re` pattern source into an equivalent Rust regex source.
///
/// - `\d` becomes an explicit class of Python's decimal digits, so matching does
///   not depend on the Unicode version of the Rust regex crates.
/// - `\<non-ASCII char>` (Python treats it as the literal char, Rust rejects it)
///   becomes the bare char.
/// - Inside a character class, `[`, `&` and `~` are escaped: Rust gives them a
///   meaning there (nested classes, `&&` and `~~` set operations), Python does not.
/// - With `verbose`, `#` comments outside classes are copied verbatim (Rust's `x`
///   flag ignores them the same way Python's `re.VERBOSE` does).
pub(crate) fn translate(src: &str, verbose: bool) -> String {
  let mut out = String::with_capacity(src.len());
  if verbose {
    out.push_str("(?x)");
  }
  let chars: Vec<char> = src.chars().collect();
  let mut i = 0;
  let mut in_class = false;
  // Index of the first char of the current class body (after `[` and `^`).
  let mut class_body_start = 0;
  while i < chars.len() {
    let c = chars[i];
    if c == '\\' && i + 1 < chars.len() {
      let n = chars[i + 1];
      if n == 'd' {
        if in_class {
          out.push_str(&DIGIT_CLASS_BODY);
        } else {
          out.push('[');
          out.push_str(&DIGIT_CLASS_BODY);
          out.push(']');
        }
      } else if !n.is_ascii() {
        out.push(n);
      } else {
        out.push('\\');
        out.push(n);
      }
      i += 2;
      continue;
    }
    if in_class {
      match c {
        ']' if i != class_body_start => {
          in_class = false;
          out.push(']');
        }
        '[' | '&' | '~' => {
          out.push('\\');
          out.push(c);
        }
        _ => out.push(c),
      }
      i += 1;
      continue;
    }
    match c {
      '[' => {
        in_class = true;
        out.push('[');
        i += 1;
        if i < chars.len() && chars[i] == '^' {
          out.push('^');
          i += 1;
        }
        class_body_start = i;
        continue;
      }
      '#' if verbose => {
        while i < chars.len() && chars[i] != '\n' {
          out.push(chars[i]);
          i += 1;
        }
        continue;
      }
      _ => out.push(c),
    }
    i += 1;
  }
  out
}

/// Whether a Python pattern needs `fancy-regex` (lookarounds or backreferences).
fn needs_fancy(src: &str) -> bool {
  if src.contains("(?=") || src.contains("(?!") || src.contains("(?<=") || src.contains("(?<!") {
    return true;
  }
  let b = src.as_bytes();
  b.windows(2)
    .any(|w| w[0] == b'\\' && w[1].is_ascii_digit() && w[1] != b'0')
}

enum Engine {
  Plain(regex::Regex),
  Fancy(fancy_regex::Regex),
}

/// A compiled Python `re` pattern (`re.compile(pattern, flags)`).
pub struct PyRegex {
  engine: Engine,
  groups: usize,
}

/// A match of a [`PyRegex`], like Python's `re.Match`.
pub struct PyMatch<'h> {
  haystack: &'h str,
  spans: Vec<Option<(usize, usize)>>,
}

impl<'h> PyMatch<'h> {
  /// `match.group(i)`: `None` when the group did not take part in the match.
  pub fn group(&self, i: usize) -> Option<&'h str> {
    self.spans[i].map(|(s, e)| &self.haystack[s..e])
  }

  /// `match.group(0)`.
  pub fn group0(&self) -> &'h str {
    self.group(0).expect("group 0 always matches")
  }

  /// `len(match.groups())`.
  pub fn groups_len(&self) -> usize {
    self.spans.len() - 1
  }
}

impl PyRegex {
  /// `re.compile(pattern)`.
  pub fn compile(pattern: &str) -> Self {
    Self::compile_flags(pattern, false)
  }

  /// `re.compile(pattern, re.VERBOSE)`.
  pub fn compile_verbose(pattern: &str) -> Self {
    Self::compile_flags(pattern, true)
  }

  fn compile_flags(pattern: &str, verbose: bool) -> Self {
    let src = translate(pattern, verbose);
    if needs_fancy(pattern) {
      let re = fancy_regex::Regex::new(&src)
        .unwrap_or_else(|e| panic!("invalid pattern {pattern:?}: {e}"));
      let groups = re.captures_len() - 1;
      Self {
        engine: Engine::Fancy(re),
        groups,
      }
    } else {
      let re =
        regex::Regex::new(&src).unwrap_or_else(|e| panic!("invalid pattern {pattern:?}: {e}"));
      let groups = re.captures_len() - 1;
      Self {
        engine: Engine::Plain(re),
        groups,
      }
    }
  }

  /// Number of capture groups (`pattern.groups`).
  pub fn groups(&self) -> usize {
    self.groups
  }

  /// All non-overlapping matches, left to right (`pattern.finditer`).
  pub fn finditer<'h>(&self, text: &'h str) -> Vec<PyMatch<'h>> {
    match &self.engine {
      Engine::Plain(re) => re
        .captures_iter(text)
        .map(|caps| PyMatch {
          haystack: text,
          spans: (0..caps.len())
            .map(|i| caps.get(i).map(|m| (m.start(), m.end())))
            .collect(),
        })
        .collect(),
      Engine::Fancy(re) => re
        .captures_iter(text)
        .map(|caps| {
          let caps = caps.expect("fancy-regex runtime error");
          PyMatch {
            haystack: text,
            spans: (0..caps.len())
              .map(|i| caps.get(i).map(|m| (m.start(), m.end())))
              .collect(),
          }
        })
        .collect(),
    }
  }

  /// `pattern.findall(text)` for a pattern with at most one capture group
  /// (an unmatched group yields `""`, like Python).
  pub fn findall(&self, text: &str) -> Vec<String> {
    assert!(
      self.groups <= 1,
      "findall with several groups returns tuples in Python"
    );
    self
      .finditer(text)
      .iter()
      .map(|m| m.group(self.groups).unwrap_or_default().to_string())
      .collect()
  }

  /// `pattern.search(text) is not None`.
  pub fn search(&self, text: &str) -> bool {
    match &self.engine {
      Engine::Plain(re) => re.is_match(text),
      Engine::Fancy(re) => re.is_match(text).expect("fancy-regex runtime error"),
    }
  }

  /// `pattern.sub(repl, text)` with a function replacement that may raise.
  pub fn sub<F>(&self, mut repl: F, text: &str) -> Result<String, Error>
  where
    F: FnMut(&PyMatch) -> Result<String, Error>,
  {
    let mut out = String::with_capacity(text.len());
    let mut last = 0;
    for m in self.finditer(text) {
      let (s, e) = m.spans[0].expect("group 0");
      out.push_str(&text[last..s]);
      out.push_str(&repl(&m)?);
      last = e;
    }
    out.push_str(&text[last..]);
    Ok(out)
  }

  /// `pattern.sub(repl, text)` with a function replacement that cannot raise.
  pub fn sub_infallible<F>(&self, mut repl: F, text: &str) -> String
  where
    F: FnMut(&PyMatch) -> String,
  {
    self.sub(|m| Ok(repl(m)), text).expect("infallible")
  }

  /// `pattern.split(text)` for a pattern without capture groups.
  pub fn split<'h>(&self, text: &'h str) -> Vec<&'h str> {
    let mut out = Vec::new();
    let mut last = 0;
    for m in self.finditer(text) {
      let (s, e) = m.spans[0].expect("group 0");
      out.push(&text[last..s]);
      last = e;
    }
    out.push(&text[last..]);
    out
  }
}

/// `str.isspace()` for a single character (Python 3.11): Unicode `Zs`, or
/// bidirectional class `WS`, `B` or `S`.
pub fn py_isspace(c: char) -> bool {
  matches!(
    c,
    '\t'
      | '\n'
      | '\x0b'
      | '\x0c'
      | '\r'
      | '\x1c'..='\x1f'
      | ' '
      | '\u{85}'
      | '\u{a0}'
      | '\u{1680}'
      | '\u{2000}'..='\u{200a}'
      | '\u{2028}'
      | '\u{2029}'
      | '\u{202f}'
      | '\u{205f}'
      | '\u{3000}'
  )
}

/// `str.strip()`.
pub fn py_strip(s: &str) -> &str {
  s.trim_matches(py_isspace)
}

/// `str.split()` (no separator: split on whitespace runs, drop empty parts).
pub fn py_split_whitespace(s: &str) -> Vec<&str> {
  s.split(py_isspace).filter(|p| !p.is_empty()).collect()
}
