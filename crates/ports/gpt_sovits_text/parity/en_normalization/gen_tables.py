"""Generate the Python `re` character class tables for `gpt_sovits_text::en_normalization`.

    pixi run --manifest-path crates/ports/gpt_sovits_text/pixi.toml data en_normalization

Writes crates/ports/gpt_sovits_text/src/en_normalization/py_tables.rs with the
code point ranges of Python 3.11 (`unicodedata.unidata_version`) for:

- `\\w` (`str.isalnum()` or `_`), which also defines `\\b`,
- `\\d` (`str.isdecimal()`),
- `\\s` (`str.isspace()`),
- the general category `Mn` (`unicodedata.category(c) == "Mn"`).
"""

import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import gpt_sovits_env  # noqa: E402

OUT = gpt_sovits_env.SRC / "en_normalization/py_tables.rs"


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, doc, rs):
    lines = [f"/// {doc}", f"pub(crate) const {name}: &[(u32, u32)] = &["]
    for a, b in rs:
        lines.append(f"  (0x{a:04X}, 0x{b:04X}),")
    lines.append("];")
    return "\n".join(lines)


def main():
    parts = [
        "//! Python `re` character classes (Unicode "
        + unicodedata.unidata_version
        + "). No Python counterpart.\n//!\n"
        "//! Generated by `parity/en_normalization/gen_tables.py`\n"
        f"//! with Python {sys.version.split()[0]}; do not edit.",
        emit("WORD", "`\\w`: `str.isalnum()` or `_`.", ranges(lambda c: c.isalnum() or c == "_")),
        emit("DIGIT", "`\\d`: `str.isdecimal()`.", ranges(str.isdecimal)),
        emit("SPACE", "`\\s`: `str.isspace()`.", ranges(str.isspace)),
        emit("MN", "`unicodedata.category(c) == \"Mn\"`.", ranges(lambda c: unicodedata.category(c) == "Mn")),
    ]
    OUT.write_text("\n\n".join(parts) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
