"""Generate src/_re_digit.rs of the `pypinyin` port crate.

pypinyin uses ``re.compile(r'\\d')`` on ``str`` patterns. In Python 3 that
matches every character in Unicode category ``Nd`` of the Unicode version
that the interpreter ships (Python 3.11 ships Unicode 14.0.0). The Rust port
uses this generated table so ``\\d`` matches exactly the same characters.

Usage: pixi run --manifest-path crates/ports/pypinyin/pixi.toml data
"""

import re
import sys
import unicodedata
from pathlib import Path

CRATE = Path(__file__).resolve().parents[1]
OUT = CRATE / "src" / "_re_digit.rs"
DIGIT = re.compile(r"\d")


def main():
    ranges = []
    start = prev = None
    for cp in range(sys.maxunicode + 1):
        if DIGIT.match(chr(cp)):
            if start is None:
                start = prev = cp
            elif cp == prev + 1:
                prev = cp
            else:
                ranges.append((start, prev))
                start = prev = cp
    if start is not None:
        ranges.append((start, prev))

    lines = [
        "// Generated by parity/gen_unicode_digits.py. Do not edit.",
        f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.",
        "",
        "//! The characters that Python's `re` module matches with `\\d` in a `str`",
        "//! pattern (Unicode category `Nd`).",
        "",
        "/// Inclusive code point ranges matched by Python `re` `\\d`.",
        "const RANGES: &[(u32, u32)] = &[",
    ]
    for a, b in ranges:
        lines.append(f"  (0x{a:05X}, 0x{b:05X}),")
    # Formatted like rustfmt with the repository rustfmt.toml (tab_spaces = 2).
    lines += [
        "];",
        "",
        "/// Port of the Python `re` `\\d` character class (`str` patterns).",
        "pub fn is_digit(c: char) -> bool {",
        "  let cp = c as u32;",
        "  RANGES",
        "    .binary_search_by(|&(lo, hi)| {",
        "      if hi < cp {",
        "        std::cmp::Ordering::Less",
        "      } else if lo > cp {",
        "        std::cmp::Ordering::Greater",
        "      } else {",
        "        std::cmp::Ordering::Equal",
        "      }",
        "    })",
        "    .is_ok()",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(ranges)} ranges)")


if __name__ == "__main__":
    main()
